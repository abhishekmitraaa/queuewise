import { CircleCheck, Info, TriangleAlert } from "lucide-react";
import type { Finding } from "../types";

interface Props {
  findings: Finding[];
  title?: string;
  intro?: string;
}

const STYLE = {
  positive: { icon: CircleCheck, color: "text-positive", bar: "bg-positive", label: "Within target" },
  caution: { icon: TriangleAlert, color: "text-caution", bar: "bg-caution", label: "Worth attention" },
  info: { icon: Info, color: "text-info", bar: "bg-info", label: "Observation" },
} as const;

export function FindingsPanel({ findings, title = "What the results mean", intro }: Props) {
  return (
    <section className="panel min-w-0 p-4" aria-labelledby="findings-title">
      <h3 id="findings-title" className="font-display text-[15px] font-semibold text-ink">
        {title}
      </h3>
      <p className="mt-0.5 text-xs text-ink-3">
        {intro ?? "Generated by fixed threshold rules from this run's measured values. Each statement lists the numbers it is based on."}
      </p>
      {findings.length === 0 ? (
        <p className="mt-4 text-sm text-ink-3">No findings for this run.</p>
      ) : (
        <ul className="mt-4 space-y-3">
          {findings.map((f) => {
            const s = STYLE[f.category];
            const Icon = s.icon;
            return (
              <li key={f.id} className="relative overflow-hidden rounded-lg border border-line bg-canvas/50 py-3 pl-4 pr-3">
                <span className={`absolute inset-y-0 left-0 w-[3px] ${s.bar}`} aria-hidden="true" />
                <div className="flex items-start gap-2.5">
                  <Icon size={17} className={`mt-0.5 shrink-0 ${s.color}`} aria-label={s.label} />
                  <div className="min-w-0 flex-1">
                    <div className="text-sm font-semibold text-ink">{f.title}</div>
                    <p className="mt-1 text-sm leading-relaxed text-ink-2">{f.description}</p>
                    {f.evidence.length > 0 && (
                      <dl className="mt-2 flex flex-wrap gap-1.5">
                        {f.evidence.map((e, i) => (
                          <div key={i} className="flex gap-1.5 rounded border border-line px-2 py-0.5 text-xs">
                            <dt className="text-ink-3">{e.label}</dt>
                            <dd className="font-medium text-ink tabular-nums">{e.value}</dd>
                          </div>
                        ))}
                      </dl>
                    )}
                  </div>
                </div>
              </li>
            );
          })}
        </ul>
      )}
    </section>
  );
}
