"""Explainable findings.

Plain-language observations generated by fixed threshold rules from measured
metrics. Every finding carries the evidence values it is based on. Nothing
here assumes which strategy "should" win; statements are conditional on the
numbers of the run(s) at hand.

Finding shape: {id, title, description, category, evidence: [{label, value}]}
with category one of "info", "positive", "caution".
"""

from __future__ import annotations

from typing import Any

from .config import RESPONSIVE_TRAFFIC_TYPES, SimulationConfig
from .strategies import STRATEGY_LABELS

# Thresholds used by the rules (documented in docs/ALGORITHM_NOTES.md).
OVERLOAD_RATIO = 1.05  # offered load > 105% of capacity = overloaded
UNDERLOAD_RATIO = 0.90  # offered load < 90% of capacity = not congested
HIGH_UTILIZATION = 0.90
FULL_BUFFER_FRACTION = 0.90  # a sample counts as "full" at >= 90% of capacity
FAIR_JAIN = 0.95
SIMILAR_ABS_MS = 1.0  # p95 differences below 1 ms or 10% count as "similar"
SIMILAR_REL = 0.10


def _ms(v: float | None) -> str:
    if v is None:
        return "n/a"
    return f"{v:.1f} ms" if v >= 1 else f"{v:.2f} ms"


def _pct(v: float | None) -> str:
    return "n/a" if v is None else f"{v * 100:.1f}%"


def _mbps(v: float | None) -> str:
    return "n/a" if v is None else f"{v:.2f} Mbps"


def _kb(v: float) -> str:
    return f"{v / 1024:.1f} KB"


def _finding(fid: str, title: str, description: str, category: str, evidence: list[tuple[str, str]]) -> dict:
    return {
        "id": fid,
        "title": title,
        "description": description,
        "category": category,
        "evidence": [{"label": label, "value": value} for label, value in evidence],
    }


def _mean(values: list[float]) -> float:
    return sum(values) / len(values) if values else 0.0


def run_findings(cfg: SimulationConfig, m: dict, per_flow: list[dict], series: list[dict]) -> list[dict]:
    out: list[dict] = []
    label = STRATEGY_LABELS[cfg.strategy]
    budget = cfg.simulation.delay_budget_ms
    capacity = cfg.link.capacity_mbps
    cap_bytes = cfg.link.queue_capacity_bytes

    if m["packets_delivered"] == 0:
        out.append(
            _finding(
                "no_delivery",
                "No packets were delivered",
                "Nothing reached the receiver before the simulation ended, so delay and throughput metrics are empty. "
                "Check that flows offer traffic and start before the end of the run.",
                "caution",
                [("Packets generated", str(m["packets_generated"]))],
            )
        )
        return out

    p95 = m["p95_queueing_delay_ms"]
    load_ratio = m["offered_load_ratio"]
    occupancy = [s["queue_occupancy_bytes"] for s in series]
    third = max(1, len(occupancy) // 3)
    early, late = _mean(occupancy[:third]), _mean(occupancy[-third:])
    responsive = any(f.traffic_type in RESPONSIVE_TRAFFIC_TYPES for f in cfg.flows)

    # Load versus capacity.
    if load_ratio > OVERLOAD_RATIO:
        text = (
            f"Flows offered {_mbps(m['offered_load_mbps'])} to a {capacity:g} Mbps link "
            f"({load_ratio * 100:.0f}% of capacity). Traffic beyond capacity must wait in the queue or be dropped."
        )
        if late > early * 1.2 and late > 0.1 * cap_bytes:
            text += f" The queue accumulated traffic: mean occupancy rose from {_kb(early)} in the first third of the run to {_kb(late)} in the last third."
        out.append(
            _finding(
                "overload",
                "Offered load exceeds the bottleneck",
                text,
                "info",
                [("Offered load", _mbps(m["offered_load_mbps"])), ("Capacity", f"{capacity:g} Mbps"), ("Load", _pct(load_ratio))],
            )
        )
    elif load_ratio < UNDERLOAD_RATIO and p95 is not None and p95 <= budget:
        out.append(
            _finding(
                "not_congested",
                "Link is not persistently congested",
                f"Offered load was {load_ratio * 100:.0f}% of capacity and p95 queueing delay stayed at {_ms(p95)}. "
                "With little standing queue, queue-management strategies have little to act on in this scenario.",
                "positive",
                [("Load", _pct(load_ratio)), ("p95 queueing delay", _ms(p95))],
            )
        )

    # Delay budget.
    viol = m["delay_budget_violation_ratio"]
    if p95 is not None and p95 > budget:
        out.append(
            _finding(
                "budget_exceeded",
                f"Queueing delay exceeded the {budget:g} ms budget",
                f"{_pct(viol)} of delivered packets waited longer than {budget:g} ms in the queue; "
                f"p95 queueing delay was {_ms(p95)} (mean {_ms(m['mean_queueing_delay_ms'])}).",
                "caution",
                [("Budget", f"{budget:g} ms"), ("Over budget", _pct(viol)), ("p95 queueing delay", _ms(p95))],
            )
        )
    elif p95 is not None:
        out.append(
            _finding(
                "budget_met",
                f"Queueing delay stayed within the {budget:g} ms budget",
                f"p95 queueing delay was {_ms(p95)}; {_pct(viol)} of delivered packets exceeded the budget.",
                "positive",
                [("Budget", f"{budget:g} ms"), ("Over budget", _pct(viol)), ("p95 queueing delay", _ms(p95))],
            )
        )

    # Bufferbloat signature: full link and a standing queue.
    util = m["link_utilization"]
    if util >= HIGH_UTILIZATION and p95 is not None and p95 > budget:
        out.append(
            _finding(
                "bufferbloat",
                "High utilization with a standing queue",
                f"{label} kept the link {util * 100:.0f}% utilized, but packets waited {_ms(m['mean_queueing_delay_ms'])} "
                f"on average. Once the link is full, a larger queue adds delay without adding throughput: "
                f"the bufferbloat signature.",
                "caution",
                [("Link utilization", _pct(util)), ("Mean queueing delay", _ms(m["mean_queueing_delay_ms"])), ("Peak queue", _kb(m["peak_queue_occupancy_bytes"]))],
            )
        )

    # Overflow pressure.
    if m["packets_dropped_overflow"] > 0:
        full = sum(1 for o in occupancy if o >= FULL_BUFFER_FRACTION * cap_bytes)
        full_frac = full / len(occupancy) if occupancy else 0.0
        out.append(
            _finding(
                "overflow",
                "Buffer overflow drops",
                f"{m['packets_dropped_overflow']:,} packets ({_pct(m['overflow_drop_ratio'])} of generated) were dropped because the "
                f"{cfg.link.queue_capacity_kb:g} KB buffer was full. The queue was at 90% of capacity or more in {_pct(full_frac)} of samples.",
                "caution" if full_frac >= 0.1 else "info",
                [("Overflow drops", f"{m['packets_dropped_overflow']:,}"), ("Samples near full", _pct(full_frac))],
            )
        )

    # AQM activity.
    if cfg.strategy != "fifo":
        if m["packets_dropped_aqm"] > 0:
            text = (
                f"{label} dropped {m['packets_dropped_aqm']:,} packets ({_pct(m['aqm_drop_ratio'])}) at dequeue after "
                f"queueing delay stayed above the {cfg.aqm.target_ms:g} ms target for at least {cfg.aqm.interval_ms:g} ms."
            )
            if not responsive and load_ratio > OVERLOAD_RATIO:
                text += (
                    " All flows here are unresponsive (they do not slow down after drops), so AQM drops cannot reduce "
                    "the arrival rate; they only replace some tail drops."
                )
            out.append(
                _finding(
                    "aqm_active",
                    "AQM dropped packets to control delay",
                    text,
                    "info",
                    [("AQM drops", f"{m['packets_dropped_aqm']:,}"), ("Target / interval", f"{cfg.aqm.target_ms:g} / {cfg.aqm.interval_ms:g} ms")],
                )
            )
        else:
            out.append(
                _finding(
                    "aqm_idle",
                    "AQM never needed to drop",
                    f"Queueing delay never stayed above the {cfg.aqm.target_ms:g} ms target for a full {cfg.aqm.interval_ms:g} ms interval.",
                    "info",
                    [("AQM drops", "0")],
                )
            )

    # Per-flow delay comparison.
    active = [f for f in per_flow if f["packets_delivered"] > 0]
    if len(active) >= 2:
        by_delay = sorted(active, key=lambda f: f["p95_queueing_delay_ms"] or 0.0)
        lo, hi = by_delay[0], by_delay[-1]
        lo_d, hi_d = lo["p95_queueing_delay_ms"] or 0.0, hi["p95_queueing_delay_ms"] or 0.0
        if hi_d > 0 and (hi_d - lo_d) <= max(SIMILAR_ABS_MS, SIMILAR_REL * hi_d):
            text = (
                f"All flows saw similar p95 queueing delay ({_ms(lo_d)} to {_ms(hi_d)})"
                + (", as expected when every flow waits behind the same shared backlog." if cfg.strategy != "fq_codel" else ".")
            )
        else:
            text = f"{lo['name']} saw p95 queueing delay of {_ms(lo_d)}, while {hi['name']} saw {_ms(hi_d)}."
            if cfg.strategy == "fq_codel":
                text += " With per-flow queues, a flow's delay depends mainly on its own backlog."
        out.append(
            _finding(
                "per_flow_delay",
                "Per-flow queueing delay",
                text,
                "info",
                [(f["name"], _ms(f["p95_queueing_delay_ms"])) for f in by_delay],
            )
        )

    # Fairness.
    jain = m["jain_fairness_index"]
    if jain is None:
        if len(cfg.flows) >= 2:
            out.append(_finding("fairness_na", "Fairness index not calculated", m.get("fairness_note") or "", "info", []))
    else:
        worst = min(
            (f for f in per_flow if f["share_of_fair_share"] is not None),
            key=lambda f: f["share_of_fair_share"],
        )
        if jain >= FAIR_JAIN:
            out.append(
                _finding(
                    "fair",
                    "Capacity shared close to max-min fair",
                    f"Jain's fairness index was {jain:.3f} (1.0 means every flow received its max-min fair share).",
                    "positive",
                    [("Jain's index", f"{jain:.3f}")],
                )
            )
        else:
            out.append(
                _finding(
                    "unfair",
                    "Capacity was not shared fairly",
                    f"Jain's fairness index was {jain:.3f}. {worst['name']} received {_mbps(worst['throughput_mbps'])}, "
                    f"{worst['share_of_fair_share'] * 100:.0f}% of its {_mbps(worst['fair_share_mbps'])} max-min fair share.",
                    "caution",
                    [("Jain's index", f"{jain:.3f}"), (f"{worst['name']} throughput", _mbps(worst["throughput_mbps"])), ("Fair share", _mbps(worst["fair_share_mbps"]))],
                )
            )
    return out


def _similar(a: float, b: float) -> bool:
    return abs(a - b) <= max(SIMILAR_ABS_MS, SIMILAR_REL * max(abs(a), abs(b)))


def comparison_findings(runs: list[dict[str, Any]], differences: list[dict]) -> list[dict]:
    """Findings comparing runs. ``runs`` are full run results."""
    out: list[dict] = []
    if len(runs) < 2:
        return out

    if differences:
        names = ", ".join(d["parameter"] for d in differences[:6])
        out.append(
            _finding(
                "not_controlled",
                "Not a controlled comparison",
                f"These runs differ in more than the queue strategy ({names}). Differences in results cannot be "
                "attributed to the strategy alone.",
                "caution",
                [("Differing parameters", str(len(differences)))],
            )
        )

    def lab(r):
        return f"{r['strategy_label']} ({r['run_id'][:6]})" if _dup_strategies else r["strategy_label"]

    _dup_strategies = len({r["strategy"] for r in runs}) < len(runs)
    baseline = next((r for r in runs if r["strategy"] == "fifo"), runs[0])
    bm = baseline["metrics"]
    responsive = any(
        f["traffic_type"] in RESPONSIVE_TRAFFIC_TYPES for r in runs for f in r["configuration"]["flows"]
    )

    # Overall similarity under low load.
    p95s = [r["metrics"]["p95_queueing_delay_ms"] for r in runs if r["metrics"]["p95_queueing_delay_ms"] is not None]
    if len(p95s) == len(runs) and all(_similar(p, p95s[0]) for p in p95s):
        load = bm["offered_load_ratio"]
        text = f"p95 queueing delay ranged only from {_ms(min(p95s))} to {_ms(max(p95s))} across strategies."
        if load < UNDERLOAD_RATIO:
            text += f" Offered load was {load * 100:.0f}% of capacity, so the queue is not persistently congested in this scenario."
        out.append(_finding("similar", "Strategies performed similarly", text, "info", [(lab(r), _ms(r["metrics"]["p95_queueing_delay_ms"])) for r in runs]))
    elif p95s:
        lowest = min(p95s)
        best = [r for r in runs if r["metrics"]["p95_queueing_delay_ms"] is not None and r["metrics"]["p95_queueing_delay_ms"] <= lowest + 1e-9]
        names = " and ".join(lab(r) for r in best)
        verb = "tied for" if len(best) > 1 else "had"
        out.append(
            _finding(
                "lowest_p95",
                f"Lowest p95 queueing delay: {names}",
                f"{names} {verb} the lowest p95 queueing delay at {_ms(lowest)}.",
                "info",
                [(lab(r), _ms(r["metrics"]["p95_queueing_delay_ms"])) for r in runs],
            )
        )

    # Each strategy against the baseline: delay vs loss vs throughput.
    for r in runs:
        if r is baseline:
            continue
        m = r["metrics"]
        b95, r95 = bm["p95_queueing_delay_ms"], m["p95_queueing_delay_ms"]
        if b95 is None or r95 is None:
            continue
        parts = [
            f"p95 queueing delay went from {_ms(b95)} with {lab(baseline)} to {_ms(r95)}",
            f"drop ratio from {_pct(bm['drop_ratio'])} to {_pct(m['drop_ratio'])}",
            f"throughput from {_mbps(bm['throughput_mbps'])} to {_mbps(m['throughput_mbps'])}.",
        ]
        text = "; ".join(parts)
        lower_delay = r95 < b95 and not _similar(r95, b95)
        more_drops = m["drop_ratio"] > bm["drop_ratio"] + 0.001
        less_tput = m["throughput_mbps"] < bm["throughput_mbps"] * 0.97
        if lower_delay and more_drops:
            text += " Lower delay was obtained by dropping more packets: the AQM trade-off."
            category = "info"
        elif lower_delay and less_tput:
            text += " Lower delay came with lower throughput"
            if responsive:
                text += ": with a short queue the link sometimes idled after the TCP-like senders backed off"
            text += "."
            category = "info"
        elif lower_delay:
            text += " Delay fell without a higher drop ratio or a notable throughput loss in this scenario."
            category = "positive"
        else:
            text += f" {lab(r)} did not reduce p95 queueing delay in this scenario."
            category = "info"
        out.append(
            _finding(
                f"vs_baseline_{r['run_id']}",
                f"{lab(r)} vs {lab(baseline)}",
                text,
                category,
                [
                    ("p95 queueing delay", f"{_ms(b95)} → {_ms(r95)}"),
                    ("Drop ratio", f"{_pct(bm['drop_ratio'])} → {_pct(m['drop_ratio'])}"),
                    ("Throughput", f"{_mbps(bm['throughput_mbps'])} → {_mbps(m['throughput_mbps'])}"),
                ],
            )
        )

    # Fairness: per-flow scheduling against the baseline.
    bj = bm["jain_fairness_index"]
    for r in runs:
        if r is baseline or r["strategy"] != "fq_codel":
            continue
        rj = r["metrics"]["jain_fairness_index"]
        if bj is None or rj is None:
            continue
        if rj > bj + 0.01:
            text = f"Per-flow scheduling raised Jain's index from {bj:.3f} to {rj:.3f}, so one flow was less able to dominate service."
            category = "positive"
        else:
            text = f"Per-flow scheduling did not improve Jain's index here ({bj:.3f} with {lab(baseline)} vs {rj:.3f})."
            category = "info"
        out.append(_finding(f"fairness_{r['run_id']}", "Fairness lens", text, category, [(lab(baseline), f"{bj:.3f}"), (lab(r), f"{rj:.3f}")]))

    # Latency-sensitive flow: the flow with the lowest configured rate.
    flows = baseline["per_flow"]
    if len(flows) >= 2:
        target = min(flows, key=lambda f: f["configured_rate_mbps"])
        values = []
        for r in runs:
            match = next((f for f in r["per_flow"] if f["flow_id"] == target["flow_id"]), None)
            if match is not None:
                values.append((lab(r), match["p95_queueing_delay_ms"], match["loss_ratio"]))
        if len(values) >= 2:
            text = f"For {target['name']} (the lowest-rate flow), p95 queueing delay was " + ", ".join(
                f"{name}: {_ms(d)}" for name, d, _ in values
            ) + "."
            out.append(
                _finding(
                    "sensitive_flow",
                    f"Impact on {target['name']}",
                    text,
                    "info",
                    [(name, f"{_ms(d)} · loss {_pct(loss)}") for name, d, loss in values],
                )
            )
    return out
